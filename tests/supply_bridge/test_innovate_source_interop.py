"""Synthetic Rust/Arrow parity with the tobac discrete cohort reference.

The fixture is not an installed Innovate binding or an empirical tobacco model.
Its boundary-time and outgoing-flow conventions apply only to this fixture.
"""

import hashlib
import json
import math
from pathlib import Path

import numpy as np
import pytest

from tobac_supply.dynamic import STATES, project_cohorts

pl = pytest.importorskip("polars", reason="synthetic Arrow parity requires the declared interchange extra")

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures" / "innovate_semi_markov"
GENERIC_STATES = ("never", "origin", "alternate", "combined", "former", "absorbing")
TOBAC_STATES = ("never_use", "smoking_only", "vaping_only", "dual_use", "former_use", "dead")
CASES = ((7, "baseline", "cohort-a", "subgroup-a", 100.0), (11, "scenario-b", "cohort-b", "subgroup-b", 50.0))


def test_synthetic_innovate_ipc_fixture_contract():
    """Pin the generated bytes, metadata, key types, uniqueness and timing."""
    arrow = FIXTURE / "cohorts.arrow"
    metadata_file = FIXTURE / "fixture.json"
    assert (
        hashlib.sha256(arrow.read_bytes()).hexdigest()
        == "64fc30c46bf669b0ae1886f431eaf9521f1f25b8c1c94fb017ffc6b341c51f9e"
    )
    assert (
        hashlib.sha256(metadata_file.read_bytes()).hexdigest()
        == "f0321a50af35906b2b3292e01d0dfd98c288308b4421815e4d042d4342922a84"
    )
    metadata = json.loads(metadata_file.read_text())
    assert metadata["states"] == list(GENERIC_STATES)
    assert metadata["cases"] == [list(case) for case in CASES]
    assert metadata["time_unit"] == "years"
    assert metadata["flow_meaning"] == "total outgoing from this state in the next interval; terminal is zero"
    assert metadata["former_max_duration_bin"] == 2
    assert metadata["intervals"] == 4
    frame = pl.read_ipc(arrow)
    assert frame.schema == {
        "draw_id": pl.UInt64,
        "scenario_id": pl.String,
        "cohort_id": pl.String,
        "subgroup": pl.String,
        "state": pl.String,
        "duration_bin": pl.UInt32,
        "time": pl.Float64,
        "occupancy": pl.Float64,
        "transition_flow": pl.Float64,
    }
    keys = ["draw_id", "scenario_id", "cohort_id", "subgroup", "state", "duration_bin", "time"]
    assert frame.height == frame.select(keys).unique().height == 80
    assert frame.null_count().sum_horizontal().item() == 0
    assert STATES == TOBAC_STATES


@pytest.mark.parametrize(("draw", "scenario", "cohort", "subgroup", "initial"), CASES)
def test_synthetic_innovate_zero_relapse_matches_tobac_and_closed_form(
    draw, scenario, cohort, subgroup, initial
):
    metadata = json.loads((FIXTURE / "fixture.json").read_text())
    frame = pl.read_ipc(FIXTURE / "cohorts.arrow").filter(
        (pl.col("draw_id") == draw)
        & (pl.col("scenario_id") == scenario)
        & (pl.col("cohort_id") == cohort)
        & (pl.col("subgroup") == subgroup)
    )
    assert frame.height == 40

    # Independent exponential competing-risk reference: annual hazards
    # 0.1 and 0.2 from smoking to vaping and former use, respectively.
    loss = -math.expm1(-0.3)
    expected_matrix = np.eye(6)
    expected_matrix[1] = [0, math.exp(-0.3), loss / 3, 0, 2 * loss / 3, 0]
    matrix = np.asarray(metadata["transition"], dtype=float)
    np.testing.assert_allclose(matrix, expected_matrix, rtol=2e-13, atol=1e-14)
    population = np.zeros((1, 6))
    population[0, 1] = initial
    reference = project_cohorts(
        initial_population=population,
        transitions=np.tile(matrix, (4, 1, 1, 1)),
        boundaries_years=np.arange(5, dtype=float),
        consumption_rates=np.zeros((4, 1, 6, 2)),
        cohort_ids=(cohort,),
        product_units=("synthetic_smoked", "synthetic_vaping"),
        policy_ids=(scenario,) * 4,
        assumption_id="synthetic_closed_cohort_v1",
    )
    for time in range(5):
        boundary = frame.filter(pl.col("time") == float(time))
        assert boundary.height == 8
        expected = [
            0.0,
            initial * math.exp(-0.3 * time),
            initial * -math.expm1(-0.3 * time) / 3,
            0.0,
            2 * initial * -math.expm1(-0.3 * time) / 3,
            0.0,
        ]
        actual = []
        for state in GENERIC_STATES:
            rows = boundary.filter(pl.col("state") == state).sort("duration_bin")
            assert rows["duration_bin"].to_list() == ([0, 1, 2] if state == "former" else [0])
            actual.append(rows["occupancy"].sum())
            flow = initial * math.exp(-0.3 * time) * loss if state == "origin" and time < 4 else 0.0
            np.testing.assert_allclose(rows["transition_flow"].to_numpy(), flow, rtol=2e-13, atol=1e-12)
        np.testing.assert_allclose(actual, expected, rtol=2e-13, atol=1e-12)
        np.testing.assert_allclose(actual, reference.population[time, 0], rtol=2e-13, atol=1e-12)

        bins = boundary.filter(pl.col("state") == "former").sort("duration_bin")["occupancy"].to_numpy()
        b0 = 2 * initial / 3 * (math.exp(-0.3 * (time - 1)) - math.exp(-0.3 * time)) if time >= 1 else 0.0
        b1 = (
            2 * initial / 3 * (math.exp(-0.3 * (time - 2)) - math.exp(-0.3 * (time - 1)))
            if time >= 2
            else 0.0
        )
        b2 = 2 * initial / 3 * -math.expm1(-0.3 * (time - 2)) if time >= 3 else 0.0
        np.testing.assert_allclose(bins, [b0, b1, b2], rtol=2e-13, atol=1e-12)
